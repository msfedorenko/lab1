#include <iostream> // підключення бібліотеки для роботи з консольним введенням/виведенням (cin, cout)
using namespace std; // використання стандартного простору імен, щоб не писати std:: перед cin та cout

int main() // головна функція програми, з якої починається її виконання
{ // початок тіла функції main
    // декларації
    float a, S;

    // введення
    cout << "a = ";
    cin >> a;

    // підрахунок
    S = a * a;   // площа квадрата S = a^2

    // виведення
    cout << "S = " << S << endl;

    // затримка екрана
    // system("pause");
    cout << "..."; // виведення трьох крапок для візуальної підказки користувачеві
    cin.get(); // зчитування символу переводу рядка (Enter), який залишився в буфері після cin >> a
    cin.get(); // очікування натискання клавіші Enter користувачем перед закриттям вікна

    return 0; // успішне завершення програми
}