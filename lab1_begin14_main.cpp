#include <iostream>  // підключення бібліотеки для роботи з консольним введенням/виведенням (cin, cout)
using namespace std; // використання стандартного простору імен

int main() // головна функція програми, з якої починається її виконання
{ // початок тіла функції main

    // 1. Декларації (оголошення змінних)
    float A, B, C, temp; // змінні дійсного типу для вхідних даних та допоміжна змінна temp

    // 2. Введення даних
    cout << "A = ";
    cin >> A;
    cout << "B = ";
    cin >> B;
    cout << "C = ";
    cin >> C;

    // 3. Підрахунок (циклічний зсув: A -> B, B -> C, C -> A)
    temp = A; // зберігаємо початкове значення A у тимчасову змінну
    A = C;    // переміщуємо вміст C в A
    C = B;    // переміщуємо вміст B в C
    B = temp; // переміщуємо збережене початкове значення A в B

    // 4. Виведення результату
    cout << "Нові значення:" << endl;
    cout << "A = " << A << endl;
    cout << "B = " << B << endl;
    cout << "C = " << C << endl;

    // 5. Затримка екрана консолі
    cout << "...";
    cin.ignore(); // очищення буфера клавіатури після введення cin >> C
    cin.get();    // очікування натискання Enter

    return 0; // успішне завершення програми
} // кінець тіла функції main